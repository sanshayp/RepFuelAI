// Helper to categorize score into completion tiers
export const getScoreCategory = (score) => {
  if (score >= 100) return 'completed';
  if (score >= 76) return 'high';
  if (score >= 51) return 'moderate';
  if (score >= 26) return 'low';
  return 'very_low';
};

